//! The published workflow document schema: it matches what `graphrt schema`
//! generates for the default build, and every example workflow validates
//! against it.
#![allow(clippy::expect_used, clippy::unwrap_used, clippy::panic)]

use std::path::{Path, PathBuf};
use std::process::Command;

use graphrt_cli::catalog::builtin_schema;
use graphrt_cli::setup;

const SCHEMA_URL: &str = "https://raw.githubusercontent.com/Graphrt/graphrt/main/schema/workflow-v1.schema.json";

fn repo() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn checked_in() -> String {
    std::fs::read_to_string(repo().join("schema/workflow-v1.schema.json")).expect("schema/workflow-v1.schema.json")
}

/// Every workflow document under `examples/` (YAML or JSON files with a top-level `graph`).
fn example_workflows() -> Vec<PathBuf> {
    fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
        for entry in std::fs::read_dir(dir).expect("read dir") {
            let path = entry.expect("entry").path();
            if path.is_dir() {
                if path.file_name().is_some_and(|n| n != "node_modules") {
                    walk(&path, out);
                }
                continue;
            }
            let ext = path.extension().and_then(|e| e.to_str()).unwrap_or_default();
            if !matches!(ext, "yaml" | "yml" | "json") {
                continue;
            }
            let text = std::fs::read_to_string(&path).expect("read");
            let value = setup::parse_structured(&text, "example").unwrap_or_default();
            if value.get("graph").is_some() {
                out.push(path);
            }
        }
    }
    let mut out = Vec::new();
    walk(&repo().join("examples"), &mut out);
    out.sort();
    out
}

/// Default features: the checked-in file is generated by this build.
#[cfg(all(
    feature = "llm",
    feature = "http",
    feature = "code",
    feature = "python",
    feature = "mcp",
    feature = "doc",
    feature = "rag",
    feature = "local-embed",
    feature = "plugins",
    feature = "wasm",
    feature = "otel",
    feature = "bundle",
    feature = "serve"
))]
#[test]
fn checked_in_schema_matches_the_default_build() {
    let generated = graphrt_cli::catalog::schema_text(&builtin_schema()).unwrap();
    assert!(
        generated == checked_in(),
        "schema/workflow-v1.schema.json is stale; regenerate it with\n  \
         cargo run -p graphrt-cli -- schema --no-default-plugins > schema/workflow-v1.schema.json"
    );
    // And the command prints the same thing.
    let out = Command::new(env!("CARGO_BIN_EXE_graphrt"))
        .args(["schema", "--no-default-plugins"])
        .env_remove("GRAPHRT_PLUGIN_PATH")
        .output()
        .expect("spawn graphrt");
    assert!(out.status.success());
    assert!(String::from_utf8_lossy(&out.stdout) == generated, "`graphrt schema` differs from builtin_schema()");
}

#[test]
fn schema_is_valid_draft_2020_12() {
    let schema: serde_json::Value = serde_json::from_str(&checked_in()).expect("schema JSON");
    assert_eq!(schema["$schema"], "https://json-schema.org/draft/2020-12/schema");
    assert_eq!(schema["$id"], SCHEMA_URL);
    jsonschema::draft202012::new(&schema).expect("valid schema");
}

#[test]
fn every_example_validates_against_the_schema() {
    let schema: serde_json::Value = serde_json::from_str(&checked_in()).expect("schema JSON");
    let validator = jsonschema::draft202012::new(&schema).expect("valid schema");
    let examples = example_workflows();
    assert!(examples.len() >= 12, "expected the example workflows, found {examples:?}");
    for path in &examples {
        let text = std::fs::read_to_string(path).expect("read");
        let value = setup::parse_structured(&text, "example").expect("parses");
        let errors: Vec<String> =
            validator.iter_errors(&value).map(|e| format!("{e} at {}", e.instance_path())).collect();
        assert!(errors.is_empty(), "{}: {errors:#?}", path.display());
        if path.extension().is_some_and(|e| e != "json") {
            let header = format!("# yaml-language-server: $schema={SCHEMA_URL}");
            assert!(text.lines().any(|l| l == header), "{} lacks the `{header}` line", path.display());
        }
    }
}

#[test]
fn schema_rejects_typos_and_unknown_types() {
    let schema = builtin_schema();
    let validator = jsonschema::draft202012::new(&schema).expect("valid schema");
    let doc = |node: serde_json::Value| serde_json::json!({"version": "1", "graph": {"nodes": [node], "edges": []}});
    assert!(validator.is_valid(&doc(serde_json::json!({"id": "t", "type": "template-transform", "template": "x"}))));
    assert!(!validator.is_valid(&doc(serde_json::json!({"id": "t", "type": "template-transform", "templat": "x"}))));
    assert!(!validator.is_valid(&doc(serde_json::json!({"id": "t", "type": "no-such-kind"}))));
    assert!(validator.is_valid(&doc(serde_json::json!({"id": "t", "type": "start", "x-position": [1, 2]}))));
    assert!(!validator.is_valid(&serde_json::json!({"version": "2", "graph": {"nodes": []}})));
}

#[test]
fn validate_reports_every_error_as_json() {
    let dir = std::env::temp_dir().join(format!("graphrt-schema-test-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("bad.yaml");
    std::fs::write(
        &path,
        "graph:\n  nodes:\n    - { id: s, type: start }\n    - { id: t, type: template-transform, templat: x }\n  edges:\n    - { source: s, target: tt }\n",
    )
    .unwrap();
    let out = Command::new(env!("CARGO_BIN_EXE_graphrt"))
        .args(["validate", "--no-default-plugins", "--format", "json", path.to_str().unwrap()])
        .output()
        .expect("spawn graphrt");
    assert_eq!(out.status.code(), Some(2));
    let report: serde_json::Value = serde_json::from_slice(&out.stdout).expect("json");
    assert_eq!(report["valid"], false);
    assert_eq!(report["errors"], 2, "{report:#}");
    let diagnostics = report["diagnostics"].as_array().unwrap();
    let field = diagnostics.iter().find(|d| d["code"] == "unknown-field").unwrap();
    assert_eq!(field["path"], "graph.nodes[1].templat");
    assert_eq!(field["suggestion"], "template");
    assert_eq!((field["line"].as_u64(), field["column"].as_u64()), (Some(4), Some(42)));
    let edge = diagnostics.iter().find(|d| d["code"] == "unknown-node").unwrap();
    assert_eq!(edge["path"], "graph.edges[0].target");
    assert_eq!(edge["suggestion"], "t");
    // The near-miss `templat` explains the missing `template`; it is not reported twice.
    assert!(!diagnostics.iter().any(|d| d["code"] == "missing-field"), "{report:#}");

    // Text output: rustc-style snippets on stderr.
    let out = Command::new(env!("CARGO_BIN_EXE_graphrt"))
        .args(["validate", "--no-default-plugins", path.to_str().unwrap()])
        .output()
        .expect("spawn graphrt");
    assert_eq!(out.status.code(), Some(2));
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("error[unknown-field]: unknown field `templat`"), "{stderr}");
    assert!(stderr.contains("bad.yaml:4:42"), "{stderr}");
    assert!(stderr.contains("did you mean `template`?"), "{stderr}");
    assert!(stderr.contains("is invalid: 2 errors"), "{stderr}");
    let _ = std::fs::remove_dir_all(&dir);
}
