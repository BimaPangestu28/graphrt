#!/usr/bin/env bash
# Builds GraphrtFFI.xcframework from crates/graphrt-ffi for the Swift package:
# iOS devices, the iOS simulator and macOS. Targets of one platform (the two
# simulator architectures, the two Mac architectures) are merged with lipo.
#
# Usage: sdk/swift/scripts/build-xcframework.sh [output.xcframework]
# Output: sdk/swift/GraphrtFFI.xcframework by default
#
# Environment (all optional):
#   GRAPHRT_TARGETS   space-separated Rust targets (default: every target below:
#                     "aarch64-apple-ios aarch64-apple-ios-sim x86_64-apple-ios
#                      aarch64-apple-darwin x86_64-apple-darwin")
#   GRAPHRT_FEATURES  cargo feature flags (default: "--features sdk", what the release ships;
#                     the JavaScript code node needs libclang, which Xcode provides)
#   GRAPHRT_PROFILE   cargo profile (default: min-size)
#   IPHONEOS_DEPLOYMENT_TARGET  minimum iOS version (default: 16.0, as in Package.swift)
#   MACOSX_DEPLOYMENT_TARGET    minimum macOS version (default: 13.0, as in Package.swift)
set -euo pipefail

export PATH="$HOME/.cargo/bin:$PATH"
export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-16.0}"
export MACOSX_DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET:-13.0}"
# The iOS SDKs ship with Xcode, not with the Command Line Tools.
if ! xcrun --sdk iphoneos --show-sdk-path >/dev/null 2>&1; then
  if [[ -d /Applications/Xcode.app/Contents/Developer ]]; then
    export DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer
  else
    echo "error: no iOS SDK found; install Xcode or point DEVELOPER_DIR at it" >&2
    exit 1
  fi
fi
# bindgen (the JavaScript code node) loads libclang; Xcode has one.
if [[ -z "${LIBCLANG_PATH:-}" ]]; then
  export LIBCLANG_PATH="$(xcode-select -p)/Toolchains/XcodeDefault.xctoolchain/usr/lib"
fi

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
package_dir="$(cd "$script_dir/.." && pwd)"
repo_root="$(cd "$package_dir/../.." && pwd)"
xcframework="${1:-$package_dir/GraphrtFFI.xcframework}"
work_dir="$repo_root/target/xcframework"
headers_dir="$work_dir/headers"

targets="${GRAPHRT_TARGETS:-aarch64-apple-ios aarch64-apple-ios-sim x86_64-apple-ios aarch64-apple-darwin x86_64-apple-darwin}"
features="${GRAPHRT_FEATURES:---features sdk}"
profile="${GRAPHRT_PROFILE:-min-size}"
target_dir="${CARGO_TARGET_DIR:-$repo_root/target}"

echo "targets:  $targets"
echo "features: $features"
echo "profile:  $profile"

cd "$repo_root"
device=() simulator=() mac=()
for target in $targets; do
  rustup target add "$target" >/dev/null
  # shellcheck disable=SC2086 # $features is a list of flags on purpose
  cargo build -p graphrt-ffi --lib --profile "$profile" --target "$target" $features
  library="$target_dir/$target/$profile/libgraphrt_ffi.a"
  case "$target" in
    *-apple-ios-sim | x86_64-apple-ios) simulator+=("$library") ;;
    *-apple-ios) device+=("$library") ;;
    *-apple-darwin) mac+=("$library") ;;
    *) echo "error: $target is not an Apple target" >&2; exit 1 ;;
  esac
done

# The C header and module map generated by UniFFI (bindings/swift); Xcode wants the
# module map to be called module.modulemap.
rm -rf "$work_dir" "$xcframework"
mkdir -p "$headers_dir"
cp bindings/swift/graphrt_ffiFFI.h "$headers_dir/"
cp bindings/swift/graphrt_ffiFFI.modulemap "$headers_dir/module.modulemap"

library_flags=()
add_platform() {
  local name="$1"
  shift
  (($# > 0)) || return 0
  local merged="$work_dir/$name/libgraphrt_ffi.a"
  mkdir -p "$work_dir/$name"
  lipo -create "$@" -output "$merged"
  library_flags+=(-library "$merged" -headers "$headers_dir")
}
add_platform ios "${device[@]+"${device[@]}"}"
add_platform ios-simulator "${simulator[@]+"${simulator[@]}"}"
add_platform macos "${mac[@]+"${mac[@]}"}"

xcodebuild -create-xcframework "${library_flags[@]}" -output "$xcframework"

echo
echo "Built $xcframework:"
find "$xcframework" -name '*.a' -exec ls -l {} \;
du -sh "$xcframework"
