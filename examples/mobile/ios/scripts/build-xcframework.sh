#!/usr/bin/env bash
# Builds GraphrtFFI.xcframework (iOS device arm64 + iOS simulator arm64) from crates/graphrt-ffi.
#
# Usage: examples/mobile/ios/scripts/build-xcframework.sh
# Output: examples/mobile/ios/build/GraphrtFFI.xcframework
#
# Environment (all optional):
#   GRAPHRT_TARGETS    space-separated Rust targets (default: "aarch64-apple-ios aarch64-apple-ios-sim")
#   GRAPHRT_FEATURES   cargo feature flags (default: "--no-default-features", enough for
#                      offline workflows; use "--features mobile-js" for the JavaScript code node)
#   GRAPHRT_PROFILE    cargo profile (default: min-size)
#   IPHONEOS_DEPLOYMENT_TARGET  minimum iOS version for the Rust objects (default: 16.0, matches the app)
set -euo pipefail

export PATH="$HOME/.cargo/bin:$PATH"
export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-16.0}"
# The iOS SDKs ship with Xcode, not with the Command Line Tools.
if ! xcrun --sdk iphoneos --show-sdk-path >/dev/null 2>&1; then
  if [[ -d /Applications/Xcode.app/Contents/Developer ]]; then
    export DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer
  else
    echo "error: no iOS SDK found; install Xcode or point DEVELOPER_DIR at it" >&2
    exit 1
  fi
fi

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
app_dir="$(cd "$script_dir/.." && pwd)"
repo_root="$(cd "$app_dir/../../.." && pwd)"
build_dir="$app_dir/build"
headers_dir="$build_dir/headers"
xcframework="$build_dir/GraphrtFFI.xcframework"

targets="${GRAPHRT_TARGETS:-aarch64-apple-ios aarch64-apple-ios-sim}"
features="${GRAPHRT_FEATURES:---no-default-features}"
profile="${GRAPHRT_PROFILE:-min-size}"
target_dir="${CARGO_TARGET_DIR:-$repo_root/target}"

echo "targets:  $targets"
echo "features: $features"
echo "profile:  $profile"

cd "$repo_root"
library_flags=()
for target in $targets; do
  rustup target add "$target" >/dev/null
  # shellcheck disable=SC2086 # $features is a list of flags on purpose
  cargo build -p graphrt-ffi --lib --profile "$profile" --target "$target" $features
  library_flags+=(-library "$target_dir/$target/$profile/libgraphrt_ffi.a" -headers "$headers_dir")
done

# The C header and module map generated by UniFFI (bindings/swift); Xcode wants the
# module map to be called module.modulemap.
rm -rf "$headers_dir" "$xcframework"
mkdir -p "$headers_dir"
cp bindings/swift/graphrt_ffiFFI.h "$headers_dir/"
cp bindings/swift/graphrt_ffiFFI.modulemap "$headers_dir/module.modulemap"

xcodebuild -create-xcframework "${library_flags[@]}" -output "$xcframework"

echo
echo "Built $xcframework:"
for target in $targets; do
  ls -l "$target_dir/$target/$profile/libgraphrt_ffi.a"
done
du -sh "$xcframework"
