#!/usr/bin/env bash
# Render the Homebrew formula for a graphrt release from its SHA256SUMS.
#
#   packaging/homebrew/render-formula.sh 0.3.0 path/to/SHA256SUMS > Formula/graphrt.rb
#
# The formula installs the prebuilt binaries from the GitHub release, so it needs
# the checksums of the four macOS/Linux archives. Publish the output to the tap
# repository Graphrt/homebrew-graphrt as Formula/graphrt.rb.
set -euo pipefail

version="${1:?usage: render-formula.sh VERSION SHA256SUMS}"
sums="${2:?usage: render-formula.sh VERSION SHA256SUMS}"

# Both values are pasted into Ruby source that `brew` evaluates, so anything
# but a plain semver version and hex digests is refused rather than quoted.
if [[ ! "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.-]+)?$ ]]; then
  echo "render-formula: \`$version\` is not a release version such as 0.4.0" >&2
  exit 1
fi
base="https://github.com/Graphrt/graphrt/releases/download/v${version}"

# Look up the checksum of one release archive.
#
# @param target - Rust target triple of the archive (string)
# @returns the hex SHA-256 on stdout
# @throws exits 1 when the archive is missing from SHA256SUMS or its digest is not 64 lowercase hex digits
checksum_for() {
  local target="$1" sum
  sum="$(awk -v name="graphrt-${target}.tar.gz" '$2 == name { print $1 }' "$sums")"
  if [[ ! "$sum" =~ ^[0-9a-f]{64}$ ]]; then
    echo "render-formula: no valid SHA-256 for graphrt-${target}.tar.gz in $sums" >&2
    exit 1
  fi
  printf '%s' "$sum"
}

# Looked up before the heredoc: a failing `$(...)` inside it would not stop
# the script, and a formula with an empty sha256 would still be printed.
sha_macos_arm="$(checksum_for aarch64-apple-darwin)"
sha_macos_intel="$(checksum_for x86_64-apple-darwin)"
sha_linux_arm="$(checksum_for aarch64-unknown-linux-musl)"
sha_linux_intel="$(checksum_for x86_64-unknown-linux-musl)"

cat <<EOF
# Generated by packaging/homebrew/render-formula.sh for graphrt ${version}.
class Graphrt < Formula
  desc "Small, fast runtime for agentic AI workflow graphs"
  homepage "https://github.com/Graphrt/graphrt"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/graphrt-aarch64-apple-darwin.tar.gz"
      sha256 "${sha_macos_arm}"
    end
    on_intel do
      url "${base}/graphrt-x86_64-apple-darwin.tar.gz"
      sha256 "${sha_macos_intel}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/graphrt-aarch64-unknown-linux-musl.tar.gz"
      sha256 "${sha_linux_arm}"
    end
    on_intel do
      url "${base}/graphrt-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${sha_linux_intel}"
    end
  end

  def install
    bin.install "graphrt"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/graphrt --version")
  end
end
EOF
